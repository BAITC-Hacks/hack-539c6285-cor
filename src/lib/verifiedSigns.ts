/**
 * Проверенная фраза: показывается ОДНИМ жестом, как у носителей, а не по словам.
 *
 * В жестовом языке фраза не равна сумме слов. «Как я могу помочь?» носители
 * показывают одним знаком ПОМОЧЬ к собеседнику с вопросом на лице, без
 * отдельных Я, МОЧЬ и КАК; по словам получилась бы калька с русского.
 */
export interface VerifiedPhrase {
  /** Файл в public/gestures без .json */
  file: string;
  /** Как фразу показать человеку: подпись в словаре */
  label: string;
  /** Что показывает аватар — глосса для строки «показываем: …» */
  gloss: string;
  /** Написания фразы: слова в нижнем регистре, без знаков препинания */
  forms: string[];
}

