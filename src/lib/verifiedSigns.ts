const byForm = new Map<string, string>();
for (const s of Object.values(VERIFIED_SIGNS)) for (const f of s.forms) byForm.set(f, s.file);

/** Проверенный жест для словоформы (в нижнем регистре) или null. */
export function resolveVerifiedSign(token: string): string | null {
  return byForm.get(token) ?? null;
}

const phraseForms = VERIFIED_PHRASES
  .flatMap((phrase) => phrase.forms.map((f) => ({ phrase, words: f.split(' ') })))
  .sort((a, b) => b.words.length - a.words.length); // сначала длинные: «как у вас дела» раньше «как дела»

export type PhraseSegment =
  | { phrase: VerifiedPhrase; words: string[] }
  | { phrase: null; words: string[] };

/**
 * Разрезать слова текста на проверенные фразы и остальное.
 *
 * Искать надо в ИСХОДНЫХ словах, до перевода в жестовый порядок: он
 * выбрасывает предлоги («как у вас дела» → «как вас дела») и переставляет
 * слова, после этого фраза уже не узнаётся.
 */
export function splitVerifiedPhrases(words: string[]): PhraseSegment[] {
  const out: PhraseSegment[] = [];
  let rest: string[] = [];
  for (let i = 0; i < words.length; ) {
    const hit = phraseForms.find((f) => f.words.every((w, k) => words[i + k] === w));
    if (hit) {
      if (rest.length) { out.push({ phrase: null, words: rest }); rest = []; }
      out.push({ phrase: hit.phrase, words: words.slice(i, i + hit.words.length) });
      i += hit.words.length;
    } else {
      rest.push(words[i]);
      i++;
    }
  }
  if (rest.length) out.push({ phrase: null, words: rest });
  return out;
}
